#!/usr/bin/env python3
"""cppview_rl.inc: the raylib names the Web Studio's C++ View may write as plain C++ in a raylib program
(function -> English++ kind of what it gives back; struct field -> kind; colours; enum constants).
Made from the same raylib 5.5 headers the C++ mode compiles against (cpp/data/cpp.json)."""
import json, sys, os, re
H = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(H, '..', 'data', 'cpp.json')))
STRUCTS = {s['name'] for s in d['structs']}
ALIAS = {'Texture2D': 'Texture', 'TextureCubemap': 'Texture', 'RenderTexture2D': 'RenderTexture', 'Camera': 'Camera3D', 'Quaternion': 'Vector4'}
def kind(c):
    c = re.sub(r'\bconst\b', '', c).strip()
    if c.endswith('*'):
        return 'txt' if re.match(r'^(char|unsigned char)\s*\*$', c) else ''
    if c == 'void': return 'now'
    if c == 'bool': return 'yno'
    if c in ('int', 'long', 'short'): return 'num'
    if c in ('unsigned int', 'unsigned short'): return 'pos'
    if c == 'unsigned char': return 'byt'
    if c == 'float': return 'flo'
    if c == 'double': return 'dec'
    if c in STRUCTS: return c
    if c in ALIAS: return c
    return ''
out = ['// GENERATED by cpp/tools/gen_cppview_rl.py from raylib 5.5 headers. Do not edit by hand.',
       '// kind "" = the C++ View writes the call but lets C++ work out its type (auto).',
       'struct RlName { const char* name; const char* kind; const char* header = ""; };']
fns = sorted({f['name']: (kind(f['ret']), {'raymath': 'raymath.h', 'rcamera': 'rcamera.h'}.get(f['lib'], '')) for f in d['functions']}.items())
rl = json.load(open(os.path.join(H, '..', '..', 'engine', 'gen', 'rlgl_api.json')))
for f in rl['functions']:
    fns.append((f['name'], (kind(f['returnType']), 'rlgl.h')))
fns = sorted(dict(fns).items())
out.append('static const RlName kRlFns[] = {'); out += ['  {"%s", "%s", "%s"},' % (k, v[0], v[1]) for k, v in fns]; out.append('};')
fl = []
for s in d['structs']:
    for f in s['fields']:
        t = f['type']
        if '[' in t: continue
        fl.append((s['name'] + '@' + f['name'], kind(t)))
for a, b in ALIAS.items():
    src = next((s for s in d['structs'] if s['name'] == b), None)
    if src:
        for f in src['fields']:
            if '[' not in f['type']: fl.append((a + '@' + f['name'], kind(f['type'])))
fl = sorted(dict(fl).items())
out.append('static const RlName kRlFields[] = {'); out += ['  {"%s", "%s"},' % kv for kv in fl]; out.append('};')
# each struct's fields in order, for Vector3{a, b, c}
order = [(st['name'], ' '.join((kind(f['type']) or '-') if '[' not in f['type'] else '-' for f in st['fields'])) for st in d['structs']]
for a, b in ALIAS.items():
    o = dict(order).get(b)
    if o is not None: order.append((a, o))
out.append('static const RlName kRlStructs[] = {'); out += ['  {"%s", "%s"},' % kv for kv in sorted(order)]; out.append('};')
cs = sorted([(c['name'], 'Color') for c in d['colors']] + [(k['name'], 'num') for k in d['constants']])
out.append('static const RlName kRlConsts[] = {'); out += ['  {"%s", "%s"},' % kv for kv in cs]; out.append('};')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
print(len(fns), 'functions,', len(fl), 'fields,', len(cs), 'constants')
