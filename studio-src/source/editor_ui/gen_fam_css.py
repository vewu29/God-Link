# Family colours for the English++ mode: 22 hues (21 families + "is"),
# each checked for >= 4.5:1 contrast on the editor backgrounds.
import colorsys
fams = list("abcdefghiklmnoprstuwx") + ["is"]
# spread hues, interleaved so neighbouring letters differ
order = [0, 11, 5, 16, 8, 19, 2, 13, 6, 17, 10, 21, 3, 14, 7, 18, 1, 12, 4, 15, 9, 20]
def lum(rgb):
    def ch(c): return c/12.92 if c <= 0.03928 else ((c+0.055)/1.055)**2.4
    r,g,b = [ch(c) for c in rgb]; return 0.2126*r+0.7152*g+0.0722*b
def contrast(a,b):
    la,lb = lum(a),lum(b); return (max(la,lb)+0.05)/(min(la,lb)+0.05)
def hexrgb(h): return tuple(int(h[i:i+2],16)/255 for i in (1,3,5))
def tohex(rgb): return "#%02x%02x%02x" % tuple(round(c*255) for c in rgb)
dark_bg = [hexrgb("#071728"), hexrgb("#0e2444")]  # editor bg + active line
light_bg = [hexrgb("#ffffff"), hexrgb("#e8f1fd")]
out_d, out_l = [], []
for i,f in enumerate(fams):
    h = (order[i]/22.0 + 0.02) % 1.0
    L = 0.72
    while True:
        rgb = colorsys.hls_to_rgb(h, L, 0.85)
        if min(contrast(rgb,b) for b in dark_bg) >= 7: break
        L += 0.01
    out_d.append((f, tohex(rgb)))
    L = 0.36
    while True:
        rgb = colorsys.hls_to_rgb(h, L, 0.9)
        if min(contrast(rgb,b) for b in light_bg) >= 5.5: break
        L -= 0.01
    out_l.append((f, tohex(rgb)))
css = "/* Family colours (generated by ui/gen_fam_css.py; contrast >= 7:1 dark, >= 5.5:1 light) */\n"
css += ":root { " + " ".join("--epp-f-%s: %s;" % (f,c) for f,c in out_l) + " }\n"
css += ':root[data-mode="dark"] { ' + " ".join("--epp-f-%s: %s;" % (f,c) for f,c in out_d) + " }\n"
css += "\n".join(".epp-f-%s { color: var(--epp-f-%s); }" % (f,f) for f in fams) + "\n"
css += ".es-fam-legend .f-is { color: var(--epp-f-is); }\n"
open("fam.css","w").write(css); print(css)
