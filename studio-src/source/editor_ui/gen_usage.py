# Counts how often each root is the second word in the Book's programs + the Studio examples.
# Output: ui/src/usage.js (ranking prior for autocomplete). Data only; changes no meaning.
import json, re, collections, os
H = os.path.dirname(os.path.abspath(__file__))
P = os.path.join(H, '..')
roots = json.load(open(os.path.join(P, 'stage_v2/data/epp-studio/roots.json')))
R = {w['word'] for w in roots['words'] if w['type'] == 'root'}
progs = [p['code'] for p in json.load(open(os.path.join(P, 'corpus/book_corpus.json')))]
ex = json.load(open(os.path.join(P, 'stage_v2/data/epp-studio/examples.json')))
progs += [it['code'] for g in ex['groups'] for it in g['items']]
c = collections.Counter()
WORD = re.compile(r'(?:"(?:[^"\\]|\\.)*"?|[^\s"])+')
for code in progs:
    for line in code.split('\n'):
        w = WORD.findall(line)
        if len(w) >= 2 and w[0] != 'note' and w[1] in R: c[w[1]] += 1
out = {k: c[k] for k in sorted(R)}
open(os.path.join(H, 'src/usage.js'), 'w').write('// Generated by ui/gen_usage.py from the Book corpus + examples: how often each root is word 2.\nexport const ROOT_USE = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(len(progs), 'programs;', sum(1 for k in out if out[k]), 'roots used')
